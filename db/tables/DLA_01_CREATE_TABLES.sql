/* ------------------------------------------------------------
   Check 1 : Objects created
   Purpose : Expect 10 rows with OBJECT_TYPE = TABLE, all owned
             by WKSP_WKSPPRDWORKSPACE, all STATUS = VALID.
   ------------------------------------------------------------ */
SELECT owner,
       object_type,
       object_name,
       status
FROM   all_objects
WHERE  owner = 'WKSP_WKSPPRDWORKSPACE'
AND    object_type = 'TABLE'
AND    object_name LIKE 'DLA\_%' ESCAPE '\'
ORDER  BY object_name;

/* ------------------------------------------------------------
   Check 2 : Seed rows
   Purpose : Expect DLA_SETTINGS = 5 and DLA_VENDORS = 5.
   ------------------------------------------------------------ */
SELECT 'DLA_SETTINGS' AS table_name,
       COUNT(*)       AS row_count
FROM   dla_settings
UNION ALL
SELECT 'DLA_VENDORS'  AS table_name,
       COUNT(*)       AS row_count
FROM   dla_vendors;
