ALTER SESSION SET CURRENT_SCHEMA = WKSP_WKSPPRDWORKSPACE;

/* ------------------------------------------------------------
   Table 1 : DLA_SETTINGS
   Purpose : Name/value settings. Holds which AI model is active
             and the connection details for each model.
   ------------------------------------------------------------ */
CREATE TABLE dla_settings (
    setting_name   VARCHAR2(50)   NOT NULL,
    setting_value  VARCHAR2(4000),
    description    VARCHAR2(500),
    updated_by     VARCHAR2(255)  DEFAULT USER NOT NULL,
    updated_on     DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT dla_settings_pk PRIMARY KEY (setting_name)
);

/* ------------------------------------------------------------
   Table 2 : DLA_VENDORS
   Purpose : Known vendors. The "is the vendor known?" check
             looks here.
   ------------------------------------------------------------ */
CREATE TABLE dla_vendors (
    vendor_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    vendor_name  VARCHAR2(200)  NOT NULL,
    active_yn    VARCHAR2(1)    DEFAULT 'Y' NOT NULL,
    created_by   VARCHAR2(255)  DEFAULT USER NOT NULL,
    created_on   DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT dla_vendors_pk PRIMARY KEY (vendor_id),
    CONSTRAINT dla_vendors_uk UNIQUE (vendor_name),
    CONSTRAINT dla_vendors_active_ck CHECK (active_yn IN ('Y', 'N'))
);

/* ------------------------------------------------------------
   Table 3 : DLA_DOCUMENTS
   Purpose : One row per uploaded file. Holds the file itself
             (BLOB) and where it is in the process.
   ------------------------------------------------------------ */
CREATE TABLE dla_documents (
    document_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    file_name    VARCHAR2(400)  NOT NULL,
    mime_type    VARCHAR2(255)  NOT NULL,
    file_blob    BLOB           NOT NULL,
    file_size    NUMBER,
    status       VARCHAR2(20)   DEFAULT 'UPLOADED' NOT NULL,
    uploaded_by  VARCHAR2(255)  DEFAULT USER NOT NULL,
    uploaded_on  DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT dla_documents_pk PRIMARY KEY (document_id),
    CONSTRAINT dla_documents_status_ck CHECK (status IN
        ('UPLOADED', 'EXTRACTED', 'IN_REVIEW', 'APPROVED', 'REJECTED', 'LOADED', 'ERROR'))
);

/* ------------------------------------------------------------
   Table 4 : DLA_EXTRACTIONS
   Purpose : One row each time a model reads a document. Records
             which model, how long it took, and the raw response.
             A document read by both models has two rows here;
             that is what the compare page will use.
   ------------------------------------------------------------ */
CREATE TABLE dla_extractions (
    extraction_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    document_id     NUMBER         NOT NULL,
    model_code      VARCHAR2(30)   NOT NULL,
    model_name      VARCHAR2(200),
    status          VARCHAR2(20)   DEFAULT 'RUNNING' NOT NULL,
    started_on      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    elapsed_ms      NUMBER,
    raw_response    CLOB,
    extracted_json  CLOB,
    error_message   VARCHAR2(4000),
    created_by      VARCHAR2(255)  DEFAULT USER NOT NULL,
    CONSTRAINT dla_extractions_pk PRIMARY KEY (extraction_id),
    CONSTRAINT dla_extractions_doc_fk FOREIGN KEY (document_id)
        REFERENCES dla_documents (document_id),
    CONSTRAINT dla_extractions_model_ck CHECK (model_code IN ('OLLAMA', 'OCI_GENAI')),
    CONSTRAINT dla_extractions_status_ck CHECK (status IN ('RUNNING', 'SUCCESS', 'ERROR')),
    CONSTRAINT dla_extractions_json_ck CHECK (extracted_json IS JSON)
);

CREATE INDEX dla_extractions_doc_ix ON dla_extractions (document_id);

/* ------------------------------------------------------------
   Table 5 : DLA_STG_HEADERS
   Purpose : Staging invoice header. The extracted data waits
             here for checks and for a person to review it.
   ------------------------------------------------------------ */
CREATE TABLE dla_stg_headers (
    stg_header_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    document_id     NUMBER         NOT NULL,
    extraction_id   NUMBER         NOT NULL,
    vendor_name     VARCHAR2(200),
    vendor_id       NUMBER,
    invoice_number  VARCHAR2(100),
    invoice_date    DATE,
    due_date        DATE,
    subtotal        NUMBER(14,2),
    tax             NUMBER(14,2),
    total           NUMBER(14,2),
    review_status   VARCHAR2(20)   DEFAULT 'PENDING' NOT NULL,
    reviewed_by     VARCHAR2(255),
    reviewed_on     DATE,
    review_comment  VARCHAR2(4000),
    created_by      VARCHAR2(255)  DEFAULT USER NOT NULL,
    created_on      DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT dla_stg_headers_pk PRIMARY KEY (stg_header_id),
    CONSTRAINT dla_stg_headers_doc_fk FOREIGN KEY (document_id)
        REFERENCES dla_documents (document_id),
    CONSTRAINT dla_stg_headers_ext_fk FOREIGN KEY (extraction_id)
        REFERENCES dla_extractions (extraction_id),
    CONSTRAINT dla_stg_headers_ven_fk FOREIGN KEY (vendor_id)
        REFERENCES dla_vendors (vendor_id),
    CONSTRAINT dla_stg_headers_status_ck CHECK (review_status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX dla_stg_headers_doc_ix ON dla_stg_headers (document_id);
CREATE INDEX dla_stg_headers_ext_ix ON dla_stg_headers (extraction_id);
CREATE INDEX dla_stg_headers_ven_ix ON dla_stg_headers (vendor_id);

/* ------------------------------------------------------------
   Table 6 : DLA_STG_LINES
   Purpose : Staging invoice lines for a staging header.
   ------------------------------------------------------------ */
CREATE TABLE dla_stg_lines (
    stg_line_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    stg_header_id  NUMBER         NOT NULL,
    line_number    NUMBER         NOT NULL,
    description    VARCHAR2(1000),
    quantity       NUMBER(14,4),
    unit_price     NUMBER(14,4),
    amount         NUMBER(14,2),
    CONSTRAINT dla_stg_lines_pk PRIMARY KEY (stg_line_id),
    CONSTRAINT dla_stg_lines_hdr_fk FOREIGN KEY (stg_header_id)
        REFERENCES dla_stg_headers (stg_header_id) ON DELETE CASCADE
);

CREATE INDEX dla_stg_lines_hdr_ix ON dla_stg_lines (stg_header_id);

/* ------------------------------------------------------------
   Table 7 : DLA_STG_FLAGS
   Purpose : One row per problem found on a staged field, for
             example field TOTAL, severity ERROR, "lines add up
             to 1,250.00 but total says 1,350.00". The review
             page shows these next to the field.
             STG_LINE_ID is empty for header-level flags.
   ------------------------------------------------------------ */
CREATE TABLE dla_stg_flags (
    flag_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    stg_header_id  NUMBER         NOT NULL,
    stg_line_id    NUMBER,
    field_name     VARCHAR2(50)   NOT NULL,
    severity       VARCHAR2(10)   NOT NULL,
    message        VARCHAR2(1000) NOT NULL,
    created_on     DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT dla_stg_flags_pk PRIMARY KEY (flag_id),
    CONSTRAINT dla_stg_flags_hdr_fk FOREIGN KEY (stg_header_id)
        REFERENCES dla_stg_headers (stg_header_id) ON DELETE CASCADE,
    CONSTRAINT dla_stg_flags_line_fk FOREIGN KEY (stg_line_id)
        REFERENCES dla_stg_lines (stg_line_id) ON DELETE CASCADE,
    CONSTRAINT dla_stg_flags_sev_ck CHECK (severity IN ('INFO', 'WARNING', 'ERROR'))
);

CREATE INDEX dla_stg_flags_hdr_ix ON dla_stg_flags (stg_header_id);
CREATE INDEX dla_stg_flags_line_ix ON dla_stg_flags (stg_line_id);

/* ------------------------------------------------------------
   Table 8 : DLA_INVOICES
   Purpose : Final invoice header. Rows arrive here only after a
             person approves the staged invoice. The unique key
             on vendor + invoice number is what makes a duplicate
             impossible to load.
   ------------------------------------------------------------ */
CREATE TABLE dla_invoices (
    invoice_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    vendor_id       NUMBER         NOT NULL,
    invoice_number  VARCHAR2(100)  NOT NULL,
    invoice_date    DATE           NOT NULL,
    due_date        DATE,
    subtotal        NUMBER(14,2),
    tax             NUMBER(14,2),
    total           NUMBER(14,2)   NOT NULL,
    document_id     NUMBER         NOT NULL,
    stg_header_id   NUMBER         NOT NULL,
    loaded_by       VARCHAR2(255)  DEFAULT USER NOT NULL,
    loaded_on       DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT dla_invoices_pk PRIMARY KEY (invoice_id),
    CONSTRAINT dla_invoices_uk UNIQUE (vendor_id, invoice_number),
    CONSTRAINT dla_invoices_ven_fk FOREIGN KEY (vendor_id)
        REFERENCES dla_vendors (vendor_id),
    CONSTRAINT dla_invoices_doc_fk FOREIGN KEY (document_id)
        REFERENCES dla_documents (document_id),
    CONSTRAINT dla_invoices_stg_fk FOREIGN KEY (stg_header_id)
        REFERENCES dla_stg_headers (stg_header_id)
);

CREATE INDEX dla_invoices_doc_ix ON dla_invoices (document_id);
CREATE INDEX dla_invoices_stg_ix ON dla_invoices (stg_header_id);

/* ------------------------------------------------------------
   Table 9 : DLA_INVOICE_LINES
   Purpose : Final invoice lines for a final invoice.
   ------------------------------------------------------------ */
CREATE TABLE dla_invoice_lines (
    invoice_line_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    invoice_id       NUMBER         NOT NULL,
    line_number      NUMBER         NOT NULL,
    description      VARCHAR2(1000),
    quantity         NUMBER(14,4),
    unit_price       NUMBER(14,4),
    amount           NUMBER(14,2),
    CONSTRAINT dla_invoice_lines_pk PRIMARY KEY (invoice_line_id),
    CONSTRAINT dla_invoice_lines_inv_fk FOREIGN KEY (invoice_id)
        REFERENCES dla_invoices (invoice_id) ON DELETE CASCADE
);

CREATE INDEX dla_invoice_lines_inv_ix ON dla_invoice_lines (invoice_id);

/* ------------------------------------------------------------
   Table 10 : DLA_AUDIT_LOG
   Purpose  : Who did what and when. DOCUMENT_ID deliberately has
              no foreign key: the log is written in its own
              transaction so entries survive a rollback, and a
              foreign key would reject entries about a document
              whose upload has not been committed yet.
   ------------------------------------------------------------ */
CREATE TABLE dla_audit_log (
    audit_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    document_id   NUMBER,
    action        VARCHAR2(50)   NOT NULL,
    details       VARCHAR2(4000),
    performed_by  VARCHAR2(255)  DEFAULT USER NOT NULL,
    performed_on  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT dla_audit_log_pk PRIMARY KEY (audit_id)
);

CREATE INDEX dla_audit_log_doc_ix ON dla_audit_log (document_id);

